import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:8000';
const out = new URL('../.impeccable/review/', import.meta.url);
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
const page = await context.newPage();
const errors = [];
const leadName = `Демо проверка браузера ${Date.now()}`;
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(base);
  await page.getByRole('heading', { name: /Создайте рабочее пространство|Вход в рабочее пространство/ }).waitFor();
  const isSetup = await page.getByRole('button', { name: 'Создать пространство', exact: true }).count();
  if (isSetup) await page.getByLabel('Имя', { exact: true }).fill('Проверка интерфейса');
  await page.getByLabel('Электронная почта', { exact: true }).fill(process.env.TEST_EMAIL || 'browser@example.test');
  await page.locator('input[name=password]').fill(process.env.TEST_PASSWORD || 'browser-check-password-2026');
  await page.getByRole('button', { name: isSetup ? 'Создать пространство' : 'Войти', exact: true }).click();
  await page.getByRole('heading', { name: 'Дашборд', exact: true }).waitFor();
  const routeBeforeSkip = page.url();
  await page.locator('.skip').focus();
  await page.locator('.skip').press('Enter');
  assert.equal(page.url(), routeBeforeSkip, 'Skip link must preserve the active route');
  assert.equal(await page.locator('main').evaluate(el => el === document.activeElement), true);
  const health = await context.request.get(`${base}/api/health`);
  assert.equal((await health.json()).demo_mode, true, 'Browser mutation checks require DEMO_MODE=true and a separate database');
  const navigation = page.locator('nav');
  for (const name of ['Новый поиск', 'База клиентов', 'Перспективные', 'CRM', 'Сотрудники', 'Аналитика', 'История поисков', 'Настройки', 'Дашборд']) {
    await navigation.getByRole('button', { name, exact: true }).click();
    await page.getByRole('heading', { name, exact: true }).waitFor();
    await page.locator('.loading').waitFor({ state: 'hidden' });
    assert.equal(await page.locator('[role=alert]').count(), 0, `${name}: unexpected alert`);
  }
  await navigation.getByRole('button', { name: 'База клиентов', exact: true }).click();
  await page.getByRole('button', { name: 'Добавить', exact: true }).click();
  await page.getByLabel('Название', { exact: true }).fill(leadName);
  await page.getByLabel('Город', { exact: true }).fill('Демонстрационный город');
  await page.getByLabel('Категория', { exact: true }).fill('Автосервисы');
  await page.getByRole('button', { name: 'Добавить организацию', exact: true }).click();
  await page.getByRole('button', { name: leadName, exact: true }).click();
  await page.getByRole('dialog').waitFor();
  await page.getByLabel('Заметки', { exact: true }).fill('Синтетическая запись для проверки сохранения.');
  await page.getByRole('button', { name: 'Сохранить карточку', exact: true }).click();
  await page.getByLabel('Комментарий', { exact: true }).fill('Проверка истории');
  await page.getByRole('dialog').getByRole('button', { name: 'Добавить', exact: true }).click();
  await page.getByText('Проверка истории', { exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Фильтры', exact: true }).click();
  await page.getByRole('button', { name: 'Фильтры', exact: true }).click();
  await page.getByLabel('Формат экспорта', { exact: true }).selectOption('json');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Экспорт', exact: true }).click();
  assert.match((await downloadPromise).suggestedFilename(), /\.json$/);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Desktop document overflow');
  await page.screenshot({ path: fileURLToPath(new URL('desktop.png', out)), fullPage: true });
  const themeButton = page.getByRole('button', { name: /Включить светлую тему|Включить тёмную тему/ });
  await themeButton.click();
  await page.screenshot({ path: fileURLToPath(new URL('light.png', out)), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile document overflow');
  await page.screenshot({ path: fileURLToPath(new URL('mobile.png', out)), fullPage: true });
  assert.deepEqual(errors, [], 'Browser errors');
  console.log('Browser smoke passed: 9 pages, create lead, notes, interaction, export, themes, mobile overflow, Escape.');
} finally {
  await browser.close();
}
